/** Documento do Cloudant para um exemplo (avaliações de 4 e 5 estrelas que chegam à média do app). */
function documentoDeExemplo(e) {
    const cincos = Math.max(0, Math.min(e.totalAvaliacoes, Math.round((e.media - 4) * e.totalAvaliacoes)));
    return {
        _id: e.id, colecao: 'publicacao', exemplo: true,
        tipo: e.tipo, titulo: e.titulo, descricao: e.descricao, autores: e.autores, ano: e.ano,
        area: e.area, subarea: e.subarea, disciplina: e.disciplina, curso: e.curso,
        instituicao: INSTITUICAO_EXEMPLOS, link: e.link, plataforma: e.plataforma, imagemLink: e.imagemLink,
        usuarioId: null,
        criadoEm: new Date(Date.now() - e.dias * 86400000).toISOString().replace(/\.\d{3}Z$/, 'Z'),
        avaliacoesBase: { soma: cincos * 5 + (e.totalAvaliacoes - cincos) * 4, total: e.totalAvaliacoes }
    };
}
