def prefixo(codigo):
    m = re.match(r'[A-Z]+', codigo)
    return m.group(0) if m else ''


def classificar(nome, codigo, curso):
    """Devolve (subárea, motivo)."""
    k = chave(nome)
    dep = prefixo(codigo)
    do_curso = subarea_do_curso(curso)
    if re.search(r'\bMEDICINA LEGAL|\bETICA MEDICA|\bDEONTOLOGIA MEDICA|\bTANATOLOGIA', k):
        return 'MEDLEG', 'nome'
    if dep in DEPTO_FORTE:
        return DEPTO_FORTE[dep], 'departamento'
    if GENERICA.search(k) and not re.search(r'\bINTERNATO\b', k):
        return do_curso, 'curso (disciplina geral)'
    for padrao, padrao_sub in DO_CURSO_TECNICO:
        if padrao.search(k):
            return (do_curso if do_curso in EXATAS_TEC else padrao_sub), 'curso técnico'
    if DIGITAL.search(k):
        return (do_curso if do_curso in ELETRICAS else 'COMP'), 'eletrônica digital'
    if SAUDE_GERAL.search(k) and not re.search(r'\bINTERNATO\b|\bVETERIN|\bANIMA', k):
        if do_curso == 'MEDCLIN' and re.search(r'SAUDE MENTAL', k):
            return 'MEDPSIQ', 'saúde'
        if do_curso == 'MEDCLIN' and re.search(r'CIRURGIC', k):
            return 'MEDCIR', 'saúde'
        return (do_curso if do_curso in SAUDE else ('PSICO' if 'MENTAL' in k else 'SCOL')), 'saúde (curso)'
    for padrao, sub in REGRAS:
        if padrao.search(k):
            if sub == 'BOT_OU_BIO':
                sub = 'BOT' if BOTANICA.search(k) else 'BIOGER'
            # Ajustes que dependem do curso.
            if sub == 'ARQURB' and re.search(r'PAISAGIS', k) and do_curso in AGRARIAS:
                sub = 'FLORIC'
            if sub == 'FITOT' and re.search(r'PLANTAS MEDICINAIS', k) and do_curso in SAUDE:
                sub = 'FARM'
            if sub == 'EDFIS' and re.search(r'CINESIOLOG|BIOMECANICA', k) and do_curso == 'FISIO':
                sub = 'FISIO'
            if sub == 'PSICO' and re.search(r'DESENVOLVIMENTO HUMANO', k) and do_curso == 'MEDCLIN':
                sub = 'MEDMI'
            if sub == 'FARM' and do_curso == 'MEDCLIN':
                sub = 'MEDPAT'
            if do_curso == 'VETCLIN':
                sub = {'MEDCLIN': 'VETCLIN', 'MEDCIR': 'VETCLIN', 'MEDRAD': 'VETCLIN', 'MEDPAT': 'VETPAT',
                       'MEDMI': 'VETREP', 'SCOL': 'VETPREV'}.get(sub, sub)
            return sub, 'nome'
    if dep in DEPTO:
        return DEPTO[dep], 'departamento (padrão)'
    return do_curso, 'curso'


