def corrigir_cp1252(texto):
    """Aspas e travessões do Windows que chegaram como caracteres de controle (\x93, \x94, \x96…)."""
    return re.sub('[\x80-\x9f]', lambda m: bytes([ord(m.group())]).decode('cp1252', errors='ignore') or ' ', texto)


def encurtar(nome, limite=150):
    """Nome que trouxe a ementa junto ("Teoria das Organizações: Conhecer e compreender…"): fica a parte antes dos dois-pontos."""
    if len(nome) > limite and ':' in nome:
        nome = nome.split(':', 1)[0].strip()
    return nome[:limite].strip()


def ler_disciplinas():
    with open(DADOS / 'disciplinas-ufsm.tsv', encoding='utf-8', newline='') as f:
        # Pula o que vier antes do cabeçalho (anotações coladas junto com a planilha).
        while True:
            linha = f.readline()
            if not linha:
                raise ValueError('cabeçalho "Curso<TAB>…" não encontrado em disciplinas-ufsm.tsv')
            if linha.startswith('Curso\t'):
                break
        cabecalho = next(csv.reader([linha], delimiter='\t', quotechar='"'))
        leitor = csv.reader(f, delimiter='\t', quotechar='"')
        assert cabecalho[0] == 'Curso' and cabecalho[8] == 'Disciplina', cabecalho
        for linha in leitor:
            if len(linha) != 14:
                raise ValueError(linha)
            yield {
                'curso': re.sub(r'\s+', ' ', linha[0]).strip(),
                'campus': linha[1].strip(),
                'codigo': linha[7].strip(),
                'nome': re.sub(r'\s+', ' ', corrigir_cp1252(linha[8])).strip(),
                'tipo': linha[11].strip(),
            }


def nome_do_curso(curso, campus):
    """Nome curto e legível do curso para mostrar no app."""
    nome = re.sub(r'^(Curso Superior de Tecnologia (em|de)|Curso de|Curso|Graduação em|Licenc\.)\s+', '', curso)
    nome = re.sub(r'/(CAMPUS|Campus)/PM$', '', nome)
    nome = re.sub(r' - CAMPUS UFSM-FW$', '', nome)
    nome = re.sub(r'/(Distância|EAD|Ead)/.*$', '', nome)
    nome = nome.replace('Tecnologia em ', '')
    if campus != 'Santa Maria':
        sigla = {'Palmeira das Missões': 'Palmeira das Missões', 'Frederico Westphalen': 'Frederico Westphalen',
                 'Cachoeira do Sul': 'Cachoeira do Sul', 'Educação a distância': 'EaD'}[campus]
        nome = f'{nome} ({sigla})'
    return re.sub(r'\s+', ' ', nome).strip()


def montar():
    total_subs = conferir_lista_enviada()
    linhas = list(ler_disciplinas())
    cursos = sorted({nome_do_curso(l['curso'], l['campus']) for l in linhas}, key=lambda c: chave(c))
    indice_curso = {c: i for i, c in enumerate(cursos)}

    # Agrupa por (subárea, nome normalizado).
    grupos = collections.OrderedDict()
    motivos = collections.Counter()
    for l in linhas:
        sub, motivo = classificar(l['nome'], l['codigo'], l['curso'])
        motivos[motivo] += 1
        k = (sub, chave(l['nome']))
        g = grupos.setdefault(k, {'variantes': collections.Counter(), 'codigos': collections.Counter(), 'cursos': set()})
        g['variantes'][l['nome']] += 1
        g['codigos'][l['codigo']] += 1
        g['cursos'].add(indice_curso[nome_do_curso(l['curso'], l['campus'])])

    por_sub = collections.defaultdict(list)
    for (sub, _), g in grupos.items():
        # Prefere a grafia com acentos; em empate, a mais frequente.
        variante = max(g['variantes'].items(), key=lambda kv: (kv[0] != sem_acento(kv[0]), kv[1]))[0]
        por_sub[sub].append({
            'nome': encurtar(titulo(variante)),
            'codigos': [c for c, _ in g['codigos'].most_common(3)],
            'cursos': sorted(g['cursos']),
        })
    for sub in por_sub:
        por_sub[sub].sort(key=lambda m: chave(m['nome']))
        # Nomes iguais depois do ajuste de maiúsculas viram um só.
        unicos = collections.OrderedDict()
        for m in por_sub[sub]:
            u = unicos.setdefault(chave(m['nome']), {'nome': m['nome'], 'codigos': [], 'cursos': set()})
            u['codigos'] = (u['codigos'] + [c for c in m['codigos'] if c not in u['codigos']])[:3]
            u['cursos'] |= set(m['cursos'])
        por_sub[sub] = [{'nome': u['nome'], 'codigos': u['codigos'], 'cursos': sorted(u['cursos'])} for u in unicos.values()]

    return linhas, cursos, por_sub, motivos, total_subs


