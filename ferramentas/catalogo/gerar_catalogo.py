def titulo(nome):
    """'QUÍMICA GERAL TEÓRICA' → 'Química Geral Teórica'; mantém siglas, romanos e letras de turma."""
    nome = re.sub(r'\s+', ' ', nome.replace('"', ' ').replace('“', ' ').replace('”', ' ')).strip()
    nome = re.sub(r'\s+([,:;)])', r'\1', nome).replace('( ', '(')
    palavras = nome.split(' ')
    saida = []
    for i, palavra in enumerate(palavras):
        nucleo = re.sub(r'^[^\wÀ-ÿ]+|[^\wÀ-ÿ]+$', '', palavra)
        inicio_frase = i == 0 or (saida and re.search(r'[:–—-]$', saida[-1]))
        if ')' in palavra and re.search(r'[A-ZÀ-Ý]{3}', palavra):
            antes, depois = palavra.split(')', 1)
            saida.append(antes + ')' + depois.lower())
            continue
        if nucleo and nucleo != nucleo.upper():          # já veio com minúsculas (ex.: "Rn")
            saida.append(palavra)
            continue
        if nucleo.upper() in NOMES_PROPRIOS:
            saida.append(palavra.replace(nucleo, NOMES_PROPRIOS[nucleo.upper()]))
            continue
        sem_vogal = len(nucleo) >= 2 and nucleo.isalpha() and not re.search(r'[AEIOUÁÉÍÓÚÂÊÔÃÕÀY]', nucleo)
        if sem_vogal or nucleo in SIGLAS or ROMANO.match(nucleo) or (len(nucleo) == 1 and i == len(palavras) - 1 and nucleo.isalpha()):
            saida.append(palavra)
            continue
        baixa = palavra.lower()
        if nucleo.lower() in MINUSCULAS and not inicio_frase:
            saida.append(baixa)
            continue
        # Primeira letra de cada parte (inclui "Sócio-Econômico" e "(Re)aprender").
        partes = re.split(r'([-/])', baixa)
        partes = [re.sub(r'^([^a-zà-ÿ]*)([a-zà-ÿ])', lambda m: m.group(1) + m.group(2).upper(), p) if p not in '-/' else p
                  for p in partes]
        saida.append(''.join(partes))
    texto = ' '.join(saida)
    return texto[0].upper() + texto[1:] if texto else texto


