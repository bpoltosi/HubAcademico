def sem_acento(texto):
    return unicodedata.normalize('NFD', texto).encode('ascii', 'ignore').decode()


def chave(texto):
    """Forma de comparação: maiúsculas, sem acentos, aspas ou espaços repetidos."""
    texto = sem_acento(texto).upper().replace('"', ' ').replace('“', ' ').replace('”', ' ')
    return re.sub(r'\s+', ' ', texto).strip()


