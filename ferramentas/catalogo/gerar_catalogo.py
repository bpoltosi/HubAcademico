def conferir_lista_enviada():
    """Confere se cada linha da lista enviada tem um par na tabela acima."""
    linhas = (DADOS / 'areas-cnpq.txt').read_text(encoding='utf-8').split('\n')
    linhas[0] = linhas[0].split('mantenha a aba matéria.')[-1]
    areas, subs = [], []
    for linha in linhas:
        texto = linha.replace('•', '').strip()
        if not texto:
            continue
        if '•' in linha:
            subs.append(texto)
        else:
            areas.append(texto)
    assert len(areas) == 8, areas
    nossos = {chave(n).replace(' ', '') for n in NOME.values()}
    faltam = []
    for s in subs:
        k = chave(s).replace(' ', '')
        k = k.replace('INFANTIIL', 'INFANTIL').replace('CLINICAE', 'CLINICAE').replace('PESQUEIRAE', 'PESQUEIROSE')
        if k not in nossos and k not in ('MEDICINA/MEDICINALEGALE', 'DEONTOLOGIA'):
            faltam.append(s)
    assert not faltam, faltam
    return len(subs)


